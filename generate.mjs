/**
 * Regenerate the example reports with `pnpm demo`.
 * The JSON inputs are the source of truth; the .report.md files are generated.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildReport } from '../src/assess.js'

const dir = dirname(fileURLToPath(import.meta.url))
const cases = [
  { input: 'pseudo-history.json', output: 'pseudo-history.report.md' },
  { input: 'excavated-bamboo.json', output: 'excavated-bamboo.report.md' },
]

for (const entry of cases) {
  const input = JSON.parse(readFileSync(join(dir, entry.input), 'utf8'))
  const report = buildReport(input)
  const header = `<!-- Generated by \`pnpm demo\` from ${entry.input}; do not edit by hand. -->\n\n`
  writeFileSync(join(dir, entry.output), header + report.markdown + '\n')
  console.log(`${entry.output}: score=${report.score} tier=${report.tier}`)
}
